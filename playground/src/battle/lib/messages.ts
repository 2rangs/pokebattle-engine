export const MESSAGES: Record<Lang, Record<Key, string>> = { ko, en }
export type MessageKey = Key

/** 문구 + {변수} 치환 */
export function msg(lang: Lang, key: Key, vars?: Vars): string {
  const s = MESSAGES[lang][key] ?? MESSAGES.ko[key] ?? key
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s
}
