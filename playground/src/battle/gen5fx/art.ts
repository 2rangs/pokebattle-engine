export type TexName = keyof typeof TEX

const P = (a: string, b: string, c: string): Palette => [hex(a), hex(b), hex(c)]
function hex(h: string): Rgb {
  const n = parseInt(h.slice(1), 16)
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255]
}

