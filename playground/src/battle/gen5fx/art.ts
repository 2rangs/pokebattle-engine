// 텍스처는 4단계 인덱스(0 투명, 1 어두움, 2 중간, 3 밝음)로 그려 두고 타입 팔레트로 색을 입힌다.
// 게임 원본 그림은 쓰지 않는다.

export type Rgb = readonly [number, number, number]
/** [어두움, 중간, 밝음] */
export type Palette = readonly [Rgb, Rgb, Rgb]

export interface Tex {
  w: number
  h: number
  /** 0~3 인덱스, 행 우선 */
  px: Uint8Array
}

function art(rows: string[]): Tex {
  const h = rows.length
  const w = Math.max(...rows.map(r => r.length))
  const px = new Uint8Array(w * h)
  rows.forEach((r, y) => [...r].forEach((c, x) => { px[y * w + x] = c === '.' || c === ' ' ? 0 : Number(c) }))
  return { w, h, px }
}

