/** 문장 첫 글자 대문자 ("the opposing X …" → "The opposing X …"). 괄호·대괄호로 시작해도 */
export function capitalizeSentences(text: string): string {
    return text.replace(/(^|[.!?…]\s+)([[(]*)(\p{Ll})/gu, (_, lead: string, pre: string, c: string) => lead + pre + c.toUpperCase())
}

